"""Provider-agnostic service contracts. Apps should depend on these, not on a concrete backend.

A future backend (Polygon, Tradier, IBKR...) only has to implement these Protocols and
register itself in `alpaca_core.client.PROVIDERS`.
"""
from __future__ import annotations

from datetime import date, datetime
from typing import Iterable, Optional, Protocol, Sequence, runtime_checkable

from .models import (Account, Activity, Bar, BarSeries, CalendarDay, Clock, CorporateAction, Movers,
                     NewsItem, OptionChain, OptionContract, Order, OrderLeg, OrderRequest, PortfolioHistory,
                     Position, Quote, Snapshot, Trade, Watchlist, Mover)

Symbols = str | Sequence[str]
When = str | date | datetime | None


@runtime_checkable
class MarketDataService(Protocol):
    def latest_quote(self, symbol: str, feed: str = "auto") -> Quote: ...
    def latest_quotes(self, symbols: Symbols, feed: str = "auto") -> dict[str, Quote]: ...
    def latest_trade(self, symbol: str, feed: str = "auto") -> Trade: ...
    def latest_trades(self, symbols: Symbols, feed: str = "auto") -> dict[str, Trade]: ...
    def latest_bar(self, symbol: str, feed: str = "auto") -> Bar: ...
    def latest_bars(self, symbols: Symbols, feed: str = "auto") -> dict[str, Bar]: ...
    def snapshot(self, symbol: str, feed: str = "auto") -> Snapshot: ...
    def snapshots(self, symbols: Symbols, feed: str = "auto") -> dict[str, Snapshot]: ...
    def bars(self, symbols: Symbols, timeframe: str = "1Day", start: When = None, end: When = None, *,
             days: Optional[int] = None, feed: str = "auto", limit: Optional[int] = None,
             last: Optional[int] = None, adjustment: str = "raw") -> BarSeries: ...
    def movers(self, top: int = 10) -> Movers: ...
    def most_actives(self, top: int = 10, by: str = "volume") -> list[Mover]: ...
    def news(self, symbols: Symbols | None = None, limit: int = 20, start: When = None, end: When = None,
             include_content: bool = False) -> list[NewsItem]: ...
    def corporate_actions(self, symbols: Symbols | None = None, types: Iterable[str] | None = None,
                          start: When = None, end: When = None) -> list[CorporateAction]: ...
    def reverse_splits(self, symbols: Symbols | None = None, start: When = None,
                       end: When = None) -> list[CorporateAction]: ...


@runtime_checkable
class OptionsDataService(Protocol):
    def contracts(self, underlying: str, expiration: When = None, *, expiration_gte: When = None,
                  expiration_lte: When = None, type: Optional[str] = None, strike_gte: Optional[float] = None,
                  strike_lte: Optional[float] = None, limit: Optional[int] = None) -> list[OptionContract]: ...
    def expirations(self, underlying: str, *, min_dte: int = 0, max_dte: Optional[int] = None) -> list[date]: ...
    def chain(self, underlying: str, expiration: When = None, *, expiration_gte: When = None,
              expiration_lte: When = None, type: Optional[str] = None,
              strike_gte: Optional[float] = None, strike_lte: Optional[float] = None,
              limit: Optional[int] = None) -> OptionChain: ...
    def snapshots(self, symbols: Symbols) -> dict[str, OptionContract]: ...
    def latest_quotes(self, symbols: Symbols) -> dict[str, Quote]: ...


@runtime_checkable
class CryptoDataService(Protocol):
    def latest_quote(self, symbol: str) -> Quote: ...
    def latest_trade(self, symbol: str) -> Trade: ...
    def bars(self, symbols: Symbols, timeframe: str = "1Hour", start: When = None, end: When = None, *,
             days: Optional[int] = None, limit: Optional[int] = None) -> BarSeries: ...
    def snapshot(self, symbol: str) -> Snapshot: ...


@runtime_checkable
class AccountService(Protocol):
    def account(self) -> Account: ...
    def positions(self) -> list[Position]: ...
    def position(self, symbol: str) -> Position: ...
    def activities(self, activity_types: Iterable[str] | None = None, after: When = None,
                   until: When = None, page_size: int = 100) -> list[Activity]: ...
    def portfolio_history(self, period: str = "1M", timeframe: str = "1D") -> PortfolioHistory: ...
    def clock(self) -> Clock: ...
    def calendar(self, start: When = None, end: When = None) -> list[CalendarDay]: ...


@runtime_checkable
class TradingService(Protocol):
    mode: str
    dry_run: bool
    def submit(self, req: OrderRequest, *, dry_run: Optional[bool] = None) -> Order: ...
    def market(self, symbol: str, side: str, qty: Optional[float] = None, notional: Optional[float] = None, **kw) -> Order: ...
    def limit(self, symbol: str, side: str, qty: float, limit_price: float, **kw) -> Order: ...
    def stop(self, symbol: str, side: str, qty: float, stop_price: float, **kw) -> Order: ...
    def stop_limit(self, symbol: str, side: str, qty: float, stop_price: float, limit_price: float, **kw) -> Order: ...
    def trailing_stop(self, symbol: str, side: str, qty: float, *, trail_percent: Optional[float] = None,
                      trail_price: Optional[float] = None, **kw) -> Order: ...
    def bracket(self, symbol: str, side: str, qty: float, *, take_profit: float, stop_loss: float,
                stop_loss_limit: Optional[float] = None, limit_price: Optional[float] = None, **kw) -> Order: ...
    def option(self, contract: str, side: str, qty: int, *, limit_price: Optional[float] = None,
               position_intent: Optional[str] = None, **kw) -> Order: ...
    def multi_leg(self, legs: Sequence[OrderLeg], qty: int, *, limit_price: Optional[float] = None, **kw) -> Order: ...
    def replace(self, order_id: str, *, qty: Optional[float] = None, limit_price: Optional[float] = None,
                stop_price: Optional[float] = None, time_in_force: Optional[str] = None,
                dry_run: Optional[bool] = None) -> Order: ...
    def cancel(self, order_id: str, *, dry_run: Optional[bool] = None) -> None: ...
    def cancel_all(self, *, dry_run: Optional[bool] = None) -> list[dict]: ...
    def get_order(self, order_id: str) -> Order: ...
    def orders(self, status: str = "open", limit: int = 50, symbols: Symbols | None = None) -> list[Order]: ...
    def close_position(self, symbol: str, *, qty: Optional[float] = None, percentage: Optional[float] = None,
                       dry_run: Optional[bool] = None) -> Order: ...
    def close_all_positions(self, *, cancel_orders: bool = True, dry_run: Optional[bool] = None) -> list[dict]: ...


@runtime_checkable
class WatchlistService(Protocol):
    def list(self) -> list[Watchlist]: ...
    def get(self, watchlist_id: str) -> Watchlist: ...
    def get_by_name(self, name: str) -> Watchlist: ...
    def create(self, name: str, symbols: Sequence[str] = ()) -> Watchlist: ...
    def update(self, watchlist_id: str, *, name: Optional[str] = None, symbols: Optional[Sequence[str]] = None) -> Watchlist: ...
    def add_symbol(self, watchlist_id: str, symbol: str) -> Watchlist: ...
    def remove_symbol(self, watchlist_id: str, symbol: str) -> Watchlist: ...
    def delete(self, watchlist_id: str) -> None: ...
